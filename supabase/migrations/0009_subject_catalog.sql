  ('QCE', 'Queensland Certificate of Education', 'Queensland', true, 4),
  ('SACE', 'South Australian Certificate of Education', 'South Australia & Northern Territory', true, 5),
  ('WACE', 'Western Australian Certificate of Education', 'Western Australia', true, 6),
  ('TCE', 'Tasmanian Certificate of Education', 'Tasmania', true, 7),
  ('ACT', 'ACT Senior Secondary Certificate', 'Australian Capital Territory', false, 8),
  ('TEST', 'Admissions & Aptitude Tests', null, null, 9);

alter table public.certificates enable row level security;
create policy "certificates public read"
  on public.certificates for select using (true);

