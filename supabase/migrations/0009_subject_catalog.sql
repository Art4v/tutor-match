-- 0009_subject_catalog.sql
-- Replaces the 17 seeded subjects (HSC + UCAT/LSAT) from 0002 with an extensive,
-- certificate-scoped Australian subject catalog. The same display name (Biology,
-- English, Physics, ...) recurs across certificates, so subjects are now scoped
-- to a certificate and the old `subjects.name` UNIQUE constraint is dropped;
-- `slug` (certificate-prefixed, e.g. 'vce-biology') stays the unique canonical key.
--
-- WIPE & RESEED: existing subjects + their tutor_subjects links are cleared. Tutors
-- re-pick subjects from the new catalog. (Pre-launch; acceptable data loss.)
--
-- 254 subjects across 9 certificate groups.

-- 1. certificates reference table --------------------------------------------

create table public.certificates (
  code           text primary key,            -- 'HSC','VCE',...,'TEST'
  name           text not null,
  jurisdiction   text,                         -- null for TEST
  external_exams boolean,                       -- null for TEST
  position       int  not null default 0
);

